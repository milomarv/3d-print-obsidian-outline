"""Config loader.

Resolution order: --config arg, then <vault>/.outline.toml, then
~/.config/3d-print-outline/config.toml, then built-in defaults. Each layer
deep-merges over the previous, so partial configs are valid.
"""

from __future__ import annotations

import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

DEFAULTS: dict[str, Any] = {
    "extensions": {
        "cad": [
            "step", "stp", "iges", "igs", "f3d", "scad", "obj",
            "sldprt", "sldasm", "slddrw", "sldlfp",
            "ipt", "x_t", "x_b", "3dm", "prt",
        ],
        "stl": ["stl"],
        "slice": ["3mf", "gcode", "bgcode"],
        "image": ["jpg", "jpeg", "png", "heic", "webp"],
    },
    "layout": {
        "project_root": "projects",
        "project_subdirs": {
            "cad": "cad",
            "stl": "stl",
            "slice": "3mf",
            "image": "images",
        },
    },
    "exclude": {
        "dirs": [".obsidian", ".trash", ".git", ".stfolder", ".stversions"],
        "globs": ["*.tmp", "~$*"],
    },
    "render": {
        "fence_begin": "<!-- BEGIN AUTO -->",
        "fence_end": "<!-- END AUTO -->",
        "header": "<!-- AUTO-GENERATED by 3d-print-outline; do not edit between AUTO fences -->",
    },
    "spoolman": {
        "base_url": "https://homenet.tale-alioth.ts.net/spoolman/api/v1",
        "ui_base_url": "https://homenet.tale-alioth.ts.net/spoolman",
        "timeout_seconds": 5,
        "enabled": True,
    },
}


@dataclass(frozen=True)
class Config:
    """Resolved configuration for a single outline run."""

    extensions: dict[str, list[str]]
    project_root: str
    project_subdirs: dict[str, str]
    exclude_dirs: set[str]
    exclude_globs: list[str]
    fence_begin: str
    fence_end: str
    header: str
    spoolman_base_url: str
    spoolman_ui_base_url: str
    spoolman_timeout: int
    spoolman_enabled: bool
    spoolman_marker_subdirs: tuple[str, ...] = field(default=())

    @property
    def marker_subdirs(self) -> tuple[str, ...]:
        return tuple(self.project_subdirs.values())


def _deep_merge(base: dict[str, Any], over: dict[str, Any]) -> dict[str, Any]:
    out = dict(base)
    for key, value in over.items():
        if (
            key in out
            and isinstance(out[key], dict)
            and isinstance(value, dict)
        ):
            out[key] = _deep_merge(out[key], value)
        else:
            out[key] = value
    return out


def _load_toml(path: Path) -> dict[str, Any]:
    with path.open("rb") as handle:
        return tomllib.load(handle)


def resolve_config(vault: Path, explicit: Path | None) -> Config:
    """Merge defaults with discovered config files and return the resolved Config."""
    layered: dict[str, Any] = DEFAULTS
    candidates: list[Path] = []
    user_home_config = Path.home() / ".config" / "3d-print-outline" / "config.toml"
    if user_home_config.exists():
        candidates.append(user_home_config)
    vault_local = vault / ".outline.toml"
    if vault_local.exists():
        candidates.append(vault_local)
    if explicit is not None:
        candidates.append(explicit)
    for path in candidates:
        layered = _deep_merge(layered, _load_toml(path))
    return _materialise(layered)


def _materialise(d: dict[str, Any]) -> Config:
    extensions = {k: list(v) for k, v in d["extensions"].items()}
    layout = d["layout"]
    exclude = d["exclude"]
    render = d["render"]
    spoolman = d["spoolman"]
    return Config(
        extensions=extensions,
        project_root=str(layout["project_root"]),
        project_subdirs=dict(layout["project_subdirs"]),
        exclude_dirs=set(exclude["dirs"]),
        exclude_globs=list(exclude["globs"]),
        fence_begin=str(render["fence_begin"]),
        fence_end=str(render["fence_end"]),
        header=str(render["header"]),
        spoolman_base_url=str(spoolman["base_url"]).rstrip("/"),
        spoolman_ui_base_url=str(spoolman["ui_base_url"]).rstrip("/"),
        spoolman_timeout=int(spoolman["timeout_seconds"]),
        spoolman_enabled=bool(spoolman["enabled"]),
    )
